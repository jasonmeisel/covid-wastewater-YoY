#!/usr/bin/env node
// Bake a reproducible pooled ridge model into the static site after the
// leakage-conscious training/backtest has refreshed .cache/wave-training-rows.json.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { fitRidge, predictRidge } from './train-wave-model.mjs';

const FEATURES = ['elapsedDays', 'logAboveThreshold', 'logBelowPeak', 'logSlope', 'slopeR2'];

async function main() {
  const input = process.argv[2] || '.cache/wave-training-rows.json';
  const output = process.argv[3] || 'js/wave-model-weights.js';
  const experiment = JSON.parse(await readFile(input, 'utf8'));
  const rows = experiment.smoothed14Rows;
  if (!Array.isArray(rows) || !rows.length) throw new Error('No chart-smoothed training rows; run tools/train-wave-model.mjs first.');
  const model = fitRidge(rows, 1);
  if (!model) throw new Error(`Insufficient rows to train model: ${rows.length}`);
  const waves = new Map();
  for (const row of rows) {
    const key = `${row.facilityUid}/${row.wavePeakDate}`;
    const group = waves.get(key) || [];
    group.push(row);
    waves.set(key, group);
  }
  const facilities = [...new Set(rows.map(row => row.facilityUid))].sort();
  const dates = rows.flatMap(row => [row.wavePeakDate, row.endDate]).sort();
  const validationErrors = [];
  for (const snapshots of waves.values()) {
    const target = snapshots.filter(row => row.x.elapsedDays >= 14)
      .sort((a, b) => a.cutoffDate.localeCompare(b.cutoffDate))[0];
    if (!target) continue;
    const training = rows.filter(row => row.facilityUid !== target.facilityUid && row.endDate < target.cutoffDate);
    const prediction = predictRidge(fitRidge(training), target.x);
    if (Number.isFinite(prediction)) validationErrors.push(Math.abs(prediction - target.remainingDays));
  }
  const baked = {
    modelVersion: 'pooled-ridge-14day-v1',
    generatedAt: experiment.generatedAt,
    source: input,
    labelDefinition: 'Confirmed sustained threshold crossing from the 14-day chart-smoothed signal; inferred closures excluded.',
    smoothingDays: 14,
    lambda: 1,
    features: FEATURES,
    means: model.means,
    scales: model.scales,
    targetMean: model.targetMean,
    coefficients: model.coefficients,
    trainingRows: rows.length,
    trainingWaves: waves.size,
    trainingFacilities: facilities,
    trainingDateRange: {
      firstPeak: dates[0],
      lastEnd: dates[dates.length - 1],
    },
    validation: {
      issuanceRule: 'First available cutoff >=14 days after peak; no decline-count requirement.',
      eligibleCompletedWaves: waves.size,
      heldOutForecasts: validationErrors.length,
      availabilityPercent: waves.size ? 100 * validationErrors.length / waves.size : null,
      meanAbsoluteErrorDays: validationErrors.length
        ? validationErrors.reduce((sum, value) => sum + value, 0) / validationErrors.length : null,
      within14DaysPercent: validationErrors.length
        ? 100 * validationErrors.filter(value => value <= 14).length / validationErrors.length : null,
      note: 'One forecast per wave with held-out facility and time constraints; point-error backtest only, no calibrated prediction interval.'
    },
  };
  const content = `// Generated by tools/build-wave-model-weights.mjs; do not edit by hand.\nexport const WAVE_END_RIDGE_MODEL = Object.freeze(${JSON.stringify(baked, null, 2)});\n`;
  await writeFile(output, content);
  console.log(JSON.stringify({ output, trainingRows: rows.length, trainingWaves: waves.size, facilities: facilities.length, validation: baked.validation }, null, 2));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
